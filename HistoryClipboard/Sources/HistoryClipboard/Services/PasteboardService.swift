import AppKit

@MainActor
final class PasteboardService {
    static let shared = PasteboardService(pasteboard: .general)

    enum PasteboardError: LocalizedError {
        case changedWhileReading
        case temporarilyUnavailable
        case writeFailed

        var errorDescription: String? {
            switch self {
            case .changedWhileReading: return "剪贴板在读取期间发生变化，将稍后重试。"
            case .temporarilyUnavailable: return "剪贴板内容暂时无法读取，将稍后重试。"
            case .writeFailed: return "无法写入系统剪贴板，请重试。"
            }
        }
    }

    static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType")
    ]

    private let pasteboard: NSPasteboard
    private let writeObjects: ([NSPasteboardWriting]) -> Bool
    private var lastWrittenChangeCount: Int?

    init(pasteboard: NSPasteboard, writeObjects: (([NSPasteboardWriting]) -> Bool)? = nil) {
        self.pasteboard = pasteboard
        self.writeObjects = writeObjects ?? { pasteboard.writeObjects($0) }
    }

    var currentChangeCount: Int { pasteboard.changeCount }

    func readSnapshot() throws -> PasteboardSnapshot {
        let count = pasteboard.changeCount
        let types = Set(pasteboard.types ?? [])
        let content: ClipboardContent?
        if count == lastWrittenChangeCount || !types.isDisjoint(with: Self.ignoredTypes) {
            content = nil
        } else if let text = pasteboard.string(forType: .string) {
            content = text.isEmpty ? nil : .text(text)
        } else if types.contains(.rtf), let data = pasteboard.data(forType: .rtf),
                  let text = NSAttributedString(rtf: data, documentAttributes: nil)?.string {
            content = text.isEmpty ? nil : .text(text)
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            content = .image(data)
        } else if !types.isDisjoint(with: [.string, .rtf, .png, .tiff]) {
            throw PasteboardError.temporarilyUnavailable
        } else {
            content = nil
        }
        guard count == pasteboard.changeCount else { throw PasteboardError.changedWhileReading }
        return PasteboardSnapshot(changeCount: count, content: content)
    }

    func write(text: String) throws {
        try performWrite([text as NSString])
    }

    func write(pngData: Data) throws {
        let item = NSPasteboardItem()
        guard item.setData(pngData, forType: .png) else { throw PasteboardError.writeFailed }
        try performWrite([item])
    }

    private func performWrite(_ objects: [NSPasteboardWriting]) throws {
        pasteboard.clearContents()
        guard writeObjects(objects) else { throw PasteboardError.writeFailed }
        lastWrittenChangeCount = pasteboard.changeCount
    }
}
